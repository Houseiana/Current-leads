export function optionLabel(options, value, t) {
  if (!value) return "-";
  const o = options.find((x) => x.value === value);
  return o && t?.[o.labelKey] ? t[o.labelKey] : value;
}

export function leadTypeLabel(value, t) {
  if (!value) return "-";
  const opt = LEAD_TYPE_OPTIONS.find((o) => o.value === value);
  if (!opt) return value;
  return t?.[opt.labelKey] || value;
}
