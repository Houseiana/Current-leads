export const LEAD_TYPE_OPTIONS = [
  { value: "Owner", labelKey: "leadTypeOwner" },
  { value: "Broker", labelKey: "leadTypeBroker" },
  { value: "Company", labelKey: "leadTypeCompany" },
];

export function leadTypeLabel(value, t) {
  if (!value) return "-";
  const opt = LEAD_TYPE_OPTIONS.find((o) => o.value === value);
  if (!opt) return value;
  return t?.[opt.labelKey] || value;
}
